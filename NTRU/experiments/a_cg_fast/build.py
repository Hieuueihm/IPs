def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def tile():
    original = ROOT/'hdl/tile/tile_thu.sv'
    s = original.read_text()
    s = s[:s.index('// Measurement wrapper:')]
    def change(a, b):
        nonlocal s
        assert a in s, a
        s = s.replace(a, b)
    change('module tile_thu #(', 'module tile_a #(')
    change('input  wire [31:0]  cfg_q, cfg_qinv,',
           'input wire [1:0] cfg_fmt,\n    input wire [3:0] cfg_shift,\n'
           '    input wire ext_fft_valid,\n    input wire [1:0] ext_fft_mpr,\n'
           '    input wire [3:0] ext_fft_mst,\n    input  wire [31:0]  cfg_q, cfg_qinv,')
    change('reg        floor_r, halve_r;', 'reg [1:0] fmt_r;\n    reg [3:0] shift_r;\n    reg        floor_r, halve_r;')
    change("floor_r <= 1'b0; halve_r <= 1'b0;", "fmt_r <= 0; shift_r <= 0; floor_r <= 1'b0; halve_r <= 1'b0;")
    change('floor_r <= cfg_floor; halve_r <= cfg_halve;', 'fmt_r <= cfg_fmt; shift_r <= cfg_shift; floor_r <= cfg_floor; halve_r <= cfg_halve;')
    change('q0[5:4]', 'fmt_r')
    change('q0[5]', 'fmt_r[1]')
    change('q0[3:0]', 'shift_r')
    change("(l1 ? 4'd8 : 4'd4)", "(w4 ? 4'd2 : l1 ? 4'd8 : 4'd4)")
    a = s.index('    function [4:0] wadr(')
    b = s.index('    // Issue slot', a)
    s = s[:a] + '''    function [3:0] wadr(input f4, input f1, input [2:0] b, input [2:0] k);
        wadr = f4 ? {b[0], k} : f1 ? {b, k[0]} : {b[1:0], k[1:0]};
    endfunction
    function [2:0] sadr(input f4, input f1, input [2:0] b, input [1:0] k);
        sadr = f4 ? {b[0], k} : f1 ? b : {b[1:0], k[0]};
    endfunction
    function [2:0] wnext(input f4, input f1, input [2:0] b);
        wnext = f4 ? {2'b0, ~b[0]} : f1 ? b + 3'd1 : {1'b0, b[1:0] + 2'd1};
    endfunction

''' + s[b:]
    change('wnext(l1,', 'wnext(w4, l1,')
    change('reg        wic, wib, wfc, wfb;', 'reg [1:0] wic, wib;\n    reg wfc, wfb;')
    change('(wbi >= wL) ? wbi - wL : wbi', '{1\'b0, wbi[2:1]}')
    change('wic <= as_co; wib <= as_bo;', 'wic[wbi[0]] <= as_co; wib[wbi[0]] <= as_bo;')
    change('&& wic :', '&& wic[wbi[0]] :')
    change('&& wib :', '&& wib[wbi[0]] :')
    change('reg  [4:0]    nwa, nra;', 'reg  [3:0]    nwa, nra;')
    for v in ('wma ', 'wmx ', 'wmw '):
        change(v+' [0:31]', v+' [0:15]')
    for v in ('wmsx', 'wmsw'):
        change(v+' [0:31]', v+' [0:7]')
    change('(wb1 >= wL)', 'wb1[0]')
    change('wim1 ? wb1 - wL : wb1', "{1'b0, wb1[2:1]}")
    change('reg  [4:0] wsa;', 'reg [2:0] wsa;\n    reg [31:0] prev_real, prev_wr;\n'
           '    wire [2:0] wsem1 = wim1 ? wk1 + wL : wk1;\n'
           '    always @(posedge clk) if (ce && v5 && mf && !wim1) begin prev_real <= a1; prev_wr <= w1; end')
    change("{1'b0, wmx[wir]}", "{1'b0, prev_real}")
    change("{1'b0, wmw[wir]}", "{1'b0, prev_wr}")
    change('wadr(w4, l1, wn1, wb1)', 'wadr(w4, l1, wn1, wsem1)')
    change('wsa <= {wn1, wk1[1:0]}', 'wsa <= sadr(w4, l1, wn1, wk1[1:0])')
    a=s.index('    reg  [3:0] wrdy;')
    b=s.index('    wire [7:0]  mt', a)
    s=s[:a]+'''    wire mbz = ext_fft_valid;
    wire [1:0] mpr = ext_fft_mpr;
    wire [3:0] mst = ext_fft_mst;
    reg [2:0] mbn;
    wire [3:0] mlst = w4 ? 4'd14 : l1 ? 4'd0 : 4'd3;
    wire mend = mbz && mpr == 2'd2 && mst == mlst;
    always @(posedge clk)
        if (rst) mbn <= 0;
        else if (ce && mend) mbn <= wnext(w4, l1, mbn);
''' +s[b:]
    change('wmsx[{mbn, mt[7:6]}]', 'wmsx[sadr(w4,l1,mbn,mt[7:6])]')
    change('wmsw[{mbn, mt[5:4]}]', 'wmsw[sadr(w4,l1,mbn,mt[5:4])]')
    s=native_tile(s)
    out=HERE/'rtl/tile_a.sv'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('// GENERATED by experiments/a_cg_fast/build.py; production SHA256 '+sha(original)+'\n'
                   '// Prototype: interleaved inputs; dense state; shared FFT product sequencer.\n'+s)
    (HERE/'rtl/mul_ss.v').write_bytes((ROOT/'hdl/mul_ss.v').read_bytes())


def native_tile(s):
    s=s.replace('module tile_a #(', 'module tile_a2 #(')
    # This is a private scheduled engine, not the autonomous production tile.
    # Core config occurs only after tile reset; fixed-rate scheduling bounds
    # buffer liveness. Keep occupancy checking in simulation, not 16 controllers.
    s=s.replace("assign idle = (inflight == 7'd0);", "assign idle = 1'b1;")
    s=s.replace('else if (en && idle) begin md <=', 'else if (en && cfg_we) begin md <=')
    at=s.index('    wire       wspace =');end=s.index(';',at)
    s=s[:at]+"    wire wspace=1'b1"+s[end:]
    at=s.index('    wire f5   = fire && mf;')+len('    wire f5   = fire && mf;')
    s=s[:at]+'''
`ifndef SYNTHESIS
    always @(posedge clk) if(!rst && fire && mf && wbf==0)
        if(wnb>=(w4 ? 2 : l1 ? 8 : 4))$fatal(1,"scheduled FFT buffer overflow");
`endif
''' +s[at:]
    s=s.replace('input wire [1:0] cfg_fmt,', 'input wire cfg_ntrugen,\n    input wire [1:0] cfg_fmt,')
    s=s.replace('reg [1:0] fmt_r;', 'reg native_r;\n    reg [1:0] fmt_r;')
    s=s.replace('fmt_r <= 0;', 'native_r <= 0; fmt_r <= 0;')
    s=s.replace('fmt_r <= cfg_fmt;', 'native_r <= cfg_ntrugen; fmt_r <= cfg_fmt;')
    s=s.replace("wire signed [67:0] winit = w4 ?", "wire signed [67:0] winit = native_r ? 68'sd0 : w4 ?")
    s=s.replace('wire [31:0] us, ud;', 'wire [31:0] us, ud;\n    wire [31:0] biased_x;')
    s=s.replace('.a(dir ? xin : side_t)', '.a(dir ? biased_x : side_t)')
    at=s.index('    always @(posedge clk) begin',s.index('wire [2:0] wki'))
    s=s[:at]+'''    // Increment A once: (A+1)+B and (A+1)-B give exactly the
    // rounded GS branches modulo 2^64, before their arithmetic right shift.
    reg [1:0] native_xcarry;
    wire [32:0] native_xinc={1'b0,xin}+{32'd0,(wki==0)||native_xcarry[wbi[0]]};
    assign biased_x=(native_r && mf && dir) ? native_xinc[31:0] : xin;
    always @(posedge clk)
        if(ce && rq_5 && native_r && dir)native_xcarry[wbi[0]]<=native_xinc[32];
''' +s[at:]
    a=s.index('    // Operand stage:')
    b=s.index('    // Modulus slot',a)
    s=s[:a]+'''    // Native NTRUGen inverse: wrap64(v+1) >>> 1 on BOTH GS
    // branches before the multiply. Reuse u_as and its interleaved carries.
    wire nh = native_r && mf && dir;
    reg v1,v5,sc1;
    reg [31:0] a1,w1,s1;
    reg [7:0] g1;
    reg [2:0] wb1,wn1;
    // The operand registers already hold each low input for one clock.
    // One delay register reuses them, replacing four indexed tiny memories.
    reg [103:0] nlo_delay;
    wire [31:0] nslo=nlo_delay[103:72],ndlo=nlo_delay[71:40];
    wire [31:0] nshi=us,ndhi=ud;
    reg [1:0] nhv;
    reg [109:0] nhp0, nhp1;
    wire nlow = rq_5 && wbi[1];
    always @(posedge clk) begin
        if (rst) nhv<=0;
        else if(ce) nhv<={nhv[0],nh && nlow};
        if(ce) begin
            nhp1<=nhp0;
            nlo_delay<={s1,a1,w1,g1};
            if(nh && nlow)
                nhp0<={wbn,wbi,rq_tag,rq_root,{nshi[31],nshi[31:1]},{ndhi[31],ndhi[31:1]}};
        end
    end
    always @(posedge clk) begin
        if(rst) begin v1<=0;v5<=0;end
        else if(ce) begin v1<=rq_ntt;v5<=nh ? (nlow||nhv[1]) : rq_5;end
        if(ce) begin
            wb1<=wbi;wn1<=wbn;
            a1<=dir ? ud : yin;s1<=dir ? us : xin;
            w1<=rq_root;g1<=rq_tag;sc1<=rq_sign;
            if(nh) begin
                sc1<=0;
                if(nlow) begin
                    a1<={ndhi[0],ndlo[31:1]};s1<={nshi[0],nslo[31:1]};
                    w1<=nlo_delay[39:8];g1<=nlo_delay[7:0];
                    wb1<=wbi-3'd2;
                end else if(nhv[1]) begin
                    {wn1,wb1,g1,w1,s1,a1}<=nhp1;
                end
            end
        end
    end

''' + s[b:]
    return s


def fixtures():
    spec=importlib.util.spec_from_file_location('cg4',ROOT/'model/cg_bank4_model.py')
    cg=importlib.util.module_from_spec(spec); spec.loader.exec_module(cg)
    sc,pc,fp=cg.sc,cg.pc,cg.fp
    sp=importlib.util.spec_from_file_location('fast_speed',ROOT/'model/a_cg_speed_estimate.py')
    speed=importlib.util.module_from_spec(sp);sp.loader.exec_module(speed)
    cases=[]
    tabs=sc.Tables()
    for (prof,ln,op),vectors in sc.golden().items():
        q=sc.PROFILES[prof][0]; hm=sc.min_stride(q,ln).bit_length()-1
        for a,z in vectors:
            cases.append((f'NTT_p{prof}_N{1<<ln}_{op}',0,0,ln,hm,op==6,q,a,z,tabs.gm[q],tabs.igm[q]))
    rng=random.Random(20261102)
    for app,q,ln,hm in list(pc.SURVEY)+[('generic31',2013265921,10,0)]:
        gm,igm=pc.tables(q,ln,hm)
        a=[rng.randrange(q) for _ in range(1<<ln)]
        z=pc.ref_forward(a,q,ln,hm)
        cases.extend([(f'{app}_forward',0,0,ln,hm,False,q,a,z,gm,igm),
                      (f'{app}_inverse',0,0,ln,hm,True,q,z,a,gm,igm)])
    for line in (ROOT/'spec/FlexTransform/1.0/assets/kernel_fixtures.jsonl').read_text().splitlines():
        d=json.loads(line);c=d['command'];fmt=c['fmt'];ln=c['logn']
        if c['op'] not in (0,1) or fmt>2: continue
        w=32*(1<<fmt)
        a=[fp.wrap(int(x,16),w) for x in d['a'][0]]
        z=[fp.wrap(int(x,16),w) for x in d['expected'][0]]
        cases.append((f'FFT{w}_N{1<<ln}_{c["op"]}',1,fmt,ln,0,c['op']==1,0,a,z,fp.roots(w),fp.roots_inv(w)))
    cases=[(*c,0) for c in cases]
    native_roots=[]
    for row in (ROOT/'spec/FlexTransform/2.0/assets/fft_ntrugen_q32_32.mem').read_text().split():
        v=int(row,16);native_roots.append((fp.wrap(v>>64,64),fp.wrap(v,64)))
    native_inverse=[(a,fp.wrap(-b,64)) for a,b in native_roots]
    for line in (ROOT/'spec/FlexTransform/2.0/assets/kernel/fft_ntrugen.jsonl').read_text().splitlines():
        d=json.loads(line);ln=d['logn'];inv=d['op']=='IFFT'
        a=[fp.wrap(int(x,16),64) for x in d['input'][0]]
        z=[fp.wrap(int(x,16),64) for x in d['expected'][0]]
        cases.append((f'NTRUGen64_{ln}_{int(inv)}',1,1,ln,0,inv,0,a,z,native_roots,native_inverse,1))
    for fn in ('synthetic.jsonl.gz','workload_512.jsonl.gz','workload_1024.jsonl.gz'):
        for line in gzip.open(ROOT/'study/vectors/r8'/fn,'rt'):
            d=json.loads(line)
            if d['type']!='kernel' or d['op'] not in ('FFT','IFFT'):continue
            ln=d['logn'];inv=d['op']=='IFFT'
            a=[fp.wrap(int(x,16),128) for x in d['a']];z=[fp.wrap(int(x,16),128) for x in d['out']]
            cases.append((f'R8_{fn}_{d["id"]}',1,2,ln,0,inv,0,a,z,fp.roots(128),fp.roots_inv(128),0))
    for pi,q,ln,gm,igm,a,z,b,iz in pc.ntrugen():
        if pi not in (0,1,161,321,322):continue
        cases.extend([(f'NTRUGenNTT_{pi}_{ln}_0',0,0,ln,0,False,q,a,z,gm,igm,0),
                      (f'NTRUGenNTT_{pi}_{ln}_1',0,0,ln,0,True,q,b,iz,gm,igm,0)])
    pack(cases,cg,speed)


def pack(cases,cg,speed,stem='fixtures'):
    words=[0x43474632,len(cases)]; manifest=[]; four_state=[];timing_cache={}
    for name,fft,fmt,ln,hm,inv,q,a,z,gm,igm,native in cases:
        chunk_start=len(words)
        fl=1<<fmt if fft else 0
        m=1<<max(0,ln-1 if fft else ln-hm)
        planes=2*fl if fft else 1<<hm
        pn=cg.plan(m,planes,inv,fl,True)
        key=(m,planes,inv,fl,native)
        if key not in timing_cache:
            old=speed.cg.FFT[2]
            if native and inv:speed.cg.FFT[2]=(12,[x+2 for x in old[1]])
            try:
                barrier=speed.plan(m,planes,inv,fl,False)
                overlapped=speed.plan(m,planes,inv,fl,True)
                timing_cache[key]=min((barrier,overlapped),key=lambda p:p['cycles'])
            finally:speed.cg.FFT[2]=old
        schedule=timing_cache[key]
        gaps=[b-a for a,b in zip(schedule['starts'],schedule['starts'][1:])]+[0]
        roots=[[] for _ in range(16)];desc=[];base=0
        for stage,layer in enumerate(pn['layers']):
            seq={}
            for e in layer: seq[e['t'],e['k']]=e['root']
            count=max(e['k'] for e in layer)+1;p=1
            while any(seq[t,k]!=seq[t,k%p] for t,k in seq): p*=2
            mask=sum(1<<t for t in sorted({e['t'] for e in layer}))
            desc.extend([mask,base,p-1,gaps[stage]])
            for t in range(16):
                for k in range(p):
                    idx=seq.get((t,k),0)
                    r=(igm if inv else gm)[idx] if idx else ((0,0) if fft else 0)
                    if fft:
                        roots[t].extend((v>>(32*j))&0xffffffff for v in r for j in range(fl))
                    else: roots[t].append(int(r)&0xffffffff)
            base+=p*(planes if fft else 1)
        assert base<=512,(name,base)
        def limbs(a):
            return [(v>>(32*j))&0xffffffff for v in a for j in range(1<<fmt if fft else 1)]
        aa,zz=limbs(a),limbs(z)
        qi=(-pow(q,-1,1<<32))&0xffffffff if q else 0
        words.extend([fft,fmt,ln,hm,int(inv),q,qi,native,len(desc)//4,base,len(aa)])
        words.extend(desc)
        for r in roots: words.extend(r)
        words.extend(aa);words.extend(zz)
        if len(four_state)<18 and ((name.startswith('NTT_p0') and ln==10) or (name.startswith('FFT') and ln==10) or (native and ln in (2,10))):
            four_state.append(words[chunk_start:])
        manifest.append(dict(name=name,fft=fft,fmt=fmt,logn=ln,hmin=hm,inverse=int(inv),
                             q=q,native=native,stages=len(desc)//4,root_words_per_lane=base,words=len(aa),gaps=gaps,model_cycles=schedule['cycles']))
    BUILD.mkdir(parents=True,exist_ok=True)
    (BUILD/(stem+'.bin')).write_bytes(struct.pack('<'+'I'*len(words),*words))
    subset=[0x43474632,len(four_state)]+[x for chunk in four_state for x in chunk]
    if stem=='fixtures':(BUILD/'four_state.bin').write_bytes(struct.pack('<'+'I'*len(subset),*subset))
    (BUILD/(stem+'.json')).write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Generated {len(cases)} cases, {len(words)*4} fixture bytes',flush=True)


if __name__=='__main__':
    BUILD.mkdir(parents=True,exist_ok=True)
    inputs=[ROOT/'hdl/tile/tile_thu.sv',ROOT/'hdl/mul_ss.v',ROOT/'hdl/core_ntt/ntt_core.sv']
    before={str(p.relative_to(ROOT)):sha(p) for p in inputs}
    manifest=BUILD/'production_hashes.json'
    if manifest.exists(): assert json.loads(manifest.read_text())==before,'Production inputs changed since prototype snapshot'
    else: manifest.write_text(json.dumps(before,indent=2)+'\n')
    tile(); fixtures()
