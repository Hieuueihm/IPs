"""Generate hdl/net/ntt_bank_net_s.sv, the structured bank -> tile network, from the source tables of
model/structured_net.py (study/results/structured_net.json).

Each port is a mux over only the sources it can ever need under the bank-indexed tile assignment:
  read, low half of x / y of tile t: list read_lo["<t>x"], read_lo["<t>y"] (16-bit banks);
  read, high half: list read_hi[...] (16-bit banks); every NTT is one 32-bit lane (format 4);
  write, bank b: list write["<b>"] of "<tile><x|y><lo|hi>" (result z0 for x, z1 for y; low or high half).
The controller gives the index into each list. Roots: P pack banks, then one of the 3 roots (as the
crossbar draft), except that child 0 of a pack (GM[g]) is only ever root 1, the root shared by every butterfly of
the first forward / last inverse layer: it comes from a register root1 loaded by the controller, so each tile picks one
of 2P + 1 roots (P banks x children 1, 2, plus root1). One register stage on every output, staggered read of x as in
the crossbar draft.

P = 4 (default): the on-array v1 design with staggered tile phases (model/staggered_net.py: 99.4% of the 16/3 rate),
module ntt_bank_net_s. Its root path also serves FFT 32 bit (tile mode 5): each pack ROM bank has two read ports, tiles
0..7 read port A and 8..15 port B, and a tile takes the 64-bit pair {child 2, child 1} of one bank (an NTT pack's two
children, or an FFT word {wi, wr}) or {0, root1}; op_w is 64 bit and loads only when load_w is set, so an FFT root read
ahead of its beats stays. The NTT child is picked by the core (low or high half). P = 8: the network the dedicated-reduction baseline needs (16 butterflies per cycle), module
ntt_bank_net_s_p8 in hdl/net/ntt_bank_net_s_p8.sv.

Run: python scripts/gen_structured_net.py [--pbanks 4|8]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TILES, BANKS = 16, 64
PB = int(sys.argv[sys.argv.index("--pbanks") + 1]) if "--pbanks" in sys.argv else 4
NAME = "ntt_bank_net_s" if PB == 4 else f"ntt_bank_net_s_p{PB}"


def width(n):
    return max(1, (n - 1).bit_length())


def main():
    tab = json.loads((ROOT / "study" / "results" / "structured_net.json").read_text())
    lo, hi, wr = tab["read_lo"], tab["read_hi"], tab["write"]
    wlo = max(width(len(v)) for v in lo.values())
    whi = max(width(len(v)) for v in hi.values())
    wwr = max(width(len(v)) for v in wr.values())
    wrt = width(2 * PB + 1)
    L = []
    say = L.append
    say("// GENERATED by scripts/gen_structured_net.py from study/results/structured_net.json; do not edit.")
    say(f"// {NAME}: structured bank -> tile network (bank-indexed tile assignment, model/structured_net.py),")
    say(f"// {PB} root-pack banks.")
    say("// Same function as hdl/net/ntt_bank_net.sv, but each port only muxes the sources it can need. The")
    say("// controller gives an index into each port's source list (see the case statements below).")
    say(f"module {NAME} #(parameter integer TILES = 16, BANKS = 64, PBANKS = {PB}) (")
    say("    input  wire                     clk, en,")
    say("    input  wire [BANKS*16-1:0]      bank_rd,")
    if PB == 4:
        say("    input  wire [2*PBANKS*64-1:0]   pack_rd,        // {child 2, child 1} of each bank: port A banks 0..3, port B")
    else:
        say("    input  wire [PBANKS*96-1:0]     pack_rd,")
    say(f"    input  wire [TILES*{wlo}-1:0]       sel_xlo, sel_ylo,")
    say(f"    input  wire [TILES*{whi}-1:0]       sel_xhi, sel_yhi,")
    say("    input  wire [TILES-1:0]         hold_x,")
    say("    input  wire [31:0]              root1,")
    if PB == 4:
        say("    input  wire [TILES*4-1:0]       sel_root,       // {root1, bank, child}; the child bit is used by the core")
        say("    input  wire [TILES-1:0]         load_w,")
        say("    output reg  [TILES*32-1:0]      op_x, op_y,")
        say("    output reg  [TILES*64-1:0]      op_w,")
    else:
        say(f"    input  wire [TILES*{wrt}-1:0]       sel_root,       // 2*bank + child - 1 (0..{2 * PB - 1}), {2 * PB} = root1")
        say("    output reg  [TILES*32-1:0]      op_x, op_y, op_w,")
    say("    input  wire [TILES*64-1:0]      tile_z,")
    say(f"    input  wire [BANKS*{wwr}-1:0]       wsel,")
    say("    input  wire [BANKS-1:0]         wen,")
    say("    output reg  [BANKS*16-1:0]      bank_wd,")
    say("    output reg  [BANKS-1:0]         bank_we")
    say(");")
    say("    function [15:0] bk(input [BANKS*16-1:0] rd, input integer b);")
    say("        bk = rd[16*b +: 16];")
    say("    endfunction")
    for t in range(TILES):
        say(f"    // tile {t}")
        for op in "xy":
            srcs = lo[f"{t}{op}"]
            say(f"    reg [15:0] {op}lo_{t};")
            say("    always @* begin")
            say(f"        case (sel_{op}lo[{wlo}*{t} +: {wlo}])")
            for i, b in enumerate(srcs):
                say(f"            {wlo}'d{i}: {op}lo_{t} = bk(bank_rd, {b});")
            say(f"            default: {op}lo_{t} = 16'd0;")
            say("        endcase")
            say("    end")
            srcs = hi[f"{t}{op}"]
            say(f"    reg [15:0] {op}hi_{t};")
            say("    always @* begin")
            if srcs:
                say(f"        case (sel_{op}hi[{whi}*{t} +: {whi}])")
                for i, b in enumerate(srcs):
                    say(f"            {whi}'d{i}: {op}hi_{t} = bk(bank_rd, {b});")
                say(f"            default: {op}hi_{t} = 16'd0;")
                say("        endcase")
            else:
                say(f"        {op}hi_{t} = 16'd0;")
            say("    end")
        say(f"    reg [31:0] xh_{t};")
        say(f"    wire [31:0] xn_{t} = {{xhi_{t}, xlo_{t}}};")
        say(f"    wire [31:0] yn_{t} = {{yhi_{t}, ylo_{t}}};")
        if PB == 4:
            port = 0 if t < 8 else 1
            say(f"    reg  [63:0] wn_{t};")
            say("    always @* begin")
            say(f"        case (sel_root[4*{t} +: 4] >> 1)")
            for b in range(PB):
                say(f"            3'd{b}: wn_{t} = pack_rd[{64 * (4 * port + b)} +: 64];")
            say(f"            default: wn_{t} = {{32'd0, root1}};")
            say("        endcase")
            say("    end")
        else:
            say(f"    reg  [31:0] wn_{t};")
            say("    always @* begin")
            say(f"        case (sel_root[{wrt}*{t} +: {wrt}])")
            for b in range(PB):
                for c in (1, 2):
                    say(f"            {wrt}'d{2 * b + c - 1}: wn_{t} = pack_rd[{96 * b + 32 * c} +: 32];")
            say(f"            default: wn_{t} = root1;")
            say("        endcase")
            say("    end")
        say("    always @(posedge clk)")
        say("        if (en) begin")
        say(f"            xh_{t} <= xn_{t};")
        say(f"            op_x[32*{t} +: 32] <= hold_x[{t}] ? xh_{t} : xn_{t};")
        say(f"            op_y[32*{t} +: 32] <= yn_{t};")
        if PB == 4:
            say(f"            if (load_w[{t}]) op_w[64*{t} +: 64] <= wn_{t};")
        else:
            say(f"            op_w[32*{t} +: 32] <= wn_{t};")
        say("        end")
    for b in range(BANKS):
        srcs = wr[str(b)]
        say(f"    // bank {b}")
        say(f"    reg [15:0] wd_{b};")
        say("    always @* begin")
        say(f"        case (wsel[{wwr}*{b} +: {wwr}])")
        for i, s in enumerate(srcs):
            t = int(s[:-3])
            op, half = s[-3], s[-2:]
            zoff = 64 * t + (32 if op == "y" else 0) + (16 if half == "hi" else 0)
            say(f"            {wwr}'d{i}: wd_{b} = tile_z[{zoff} +: 16];")
        say(f"            default: wd_{b} = 16'd0;")
        say("        endcase")
        say("    end")
        say("    always @(posedge clk)")
        say(f"        if (en) begin bank_wd[16*{b} +: 16] <= wd_{b}; bank_we[{b}] <= wen[{b}]; end")
    say("endmodule")
    out = ROOT / "hdl" / "net" / f"{NAME}.sv"
    out.write_text("\n".join(L) + "\n", encoding="ascii", newline="\n")
    if PB != 4:
        print(f"wrote {out}: {PB} pack banks, root select {wrt} bits")
        return
    # source lists for the testbench: [count, s0, s1, ...] padded to 17 entries per port
    inc = ["// GENERATED by scripts/gen_structured_net.py; source lists of ntt_bank_net_s for the testbench."]
    def arr(name, rows):
        flat = []
        for r in rows:
            flat += [len(r)] + list(r) + [0] * (16 - len(r))
        inc.append(f"integer {name} [0:{len(flat) - 1}];")
        inc.append("initial begin")
        inc.extend(f"    {name}[{i}] = {v};" for i, v in enumerate(flat))
        inc.append("end")
    arr("LO_SRC", [lo[f"{t}{op}"] for t in range(TILES) for op in "xy"])
    arr("HI_SRC", [hi[f"{t}{op}"] for t in range(TILES) for op in "xy"])
    def code(s):
        t = int(s[:-3])
        return 64 * t + (32 if s[-3] == "y" else 0) + (16 if s[-2:] == "hi" else 0)
    arr("WR_SRC", [[code(s) for s in wr[str(b)]] for b in range(BANKS)])
    (ROOT / "sim" / "net" / "structured_lists.svh").write_text("\n".join(inc) + "\n", encoding="ascii", newline="\n")
    meta = {"sel_lo_bits": wlo, "sel_hi_bits": whi, "wsel_bits": wwr, "pack_banks": PB, "sel_root_bits": wrt}
    (ROOT / "hdl" / "net" / "ntt_bank_net_s.json").write_text(json.dumps(meta) + "\n")
    print(f"wrote {out}: sel_lo {wlo} bits, sel_hi {whi} bits, wsel {wwr} bits, {PB} pack banks, root select {wrt} bits")


if __name__ == "__main__":
    main()
