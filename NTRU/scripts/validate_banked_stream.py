"""Bank RAM model -> actual RTL gather/array/scatter under mixed contexts/stalls."""
import json
from random import Random
import sys
from arith_experiment_common import ROOT,hashes
sys.path.insert(0,str(ROOT))
from model import ntt_banked_supply as supply
from validate_flex_stream import generate,simulate,DEPENDENCIES


def main():
    rng=Random(20261026);vectors=[];cases=[]
    for q,sizes in ((12289,(8,16,32,64,128,256,512,1024)),(3329,(8,16,32,64,128,256))):
        for n in sizes:
            for inverse in (False,True):
                cases.append(supply.run_case(q,n,q==3329 and n==256,inverse,rng,vectors))
    ntt_count=len(vectors)
    units,_,_,_,_=generate()
    vectors.extend((*v,0,0) for v in units if not v[0] and v[1] in (0,1,2) and len(vectors)<ntt_count+952)
    rng.shuffle(vectors)
    _,stats=simulate(vectors,'banked',1,1,banked=1)
    result={'ntt_transactions':ntt_count,'transform_cases':len(cases),'simulation':stats,'mismatches':0,
            'source_sha256':hashes([*DEPENDENCIES,'hdl/proto/ntt_bank_permute64.sv',
                                    'model/ntt_banked_supply.py','scripts/validate_banked_stream.py']),
            'scope':'Actual combinational bank gather/scatter + FIFO + 16-tile array; RAM rows/requests are generated by Python, not a hardware stage controller.'}
    (ROOT/'study/results/banked_stream_validation.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result,indent=2))


if __name__=='__main__':main()
